"""Reproducible Windows build: one command locally and on GitHub Actions.

    python build/build.py            # PyInstaller folder build + portable ZIP + installer
    python build/build.py --no-installer

Steps:
1. Generate the Windows version resource from ``desktop_organizer.__version__``.
2. Run PyInstaller (one-folder build, windowed, with icon and version metadata).
3. Pack the portable ZIP (the folder plus an empty ``data`` folder that switches the app
   into portable mode).
4. Compile the per-user installer with Inno Setup (``iscc`` must be on PATH or in the
   default install location).
5. Write SHA-256 checksums for all release files.

Outputs go to ``dist/``.
"""

from __future__ import annotations

import argparse
import hashlib
import os
import re
import shutil
import subprocess
import sys
import zipfile
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BUILD = ROOT / "build"
DIST = ROOT / "dist"
WORK = ROOT / "build" / "_work"
APP_EXE = "DesktopOrganizer"
PUBLISHER = "Desktop Organizer contributors"


def read_version() -> str:
    text = (ROOT / "src" / "desktop_organizer" / "__init__.py").read_text(encoding="utf-8")
    match = re.search(r'^__version__ = "(\d+)\.(\d+)\.(\d+)"$', text, re.MULTILINE)
    if not match:
        raise SystemExit("Could not read __version__ (expected MAJOR.MINOR.PATCH)")
    return ".".join(match.groups())


def write_version_file(version: str) -> Path:
    major, minor, patch = (int(p) for p in version.split("."))
    year = date.today().year
    content = f"""# Generated by build/build.py. Do not edit.
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers=({major}, {minor}, {patch}, 0),
    prodvers=({major}, {minor}, {patch}, 0),
    mask=0x3f, flags=0x0, OS=0x40004, fileType=0x1, subtype=0x0, date=(0, 0)),
  kids=[
    StringFileInfo([StringTable('040904B0', [
      StringStruct('CompanyName', '{PUBLISHER}'),
      StringStruct('FileDescription', 'Desktop Organizer'),
      StringStruct('FileVersion', '{version}'),
      StringStruct('InternalName', '{APP_EXE}'),
      StringStruct('LegalCopyright', 'Copyright (c) {year} {PUBLISHER}. MIT License.'),
      StringStruct('OriginalFilename', '{APP_EXE}.exe'),
      StringStruct('ProductName', 'Desktop Organizer'),
      StringStruct('ProductVersion', '{version}')])]),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
"""
    WORK.mkdir(parents=True, exist_ok=True)
    target = WORK / "version_info.txt"
    target.write_text(content, encoding="utf-8")
    return target


def run_pyinstaller(version_file: Path) -> Path:
    resources = ROOT / "src" / "desktop_organizer" / "resources"
    sep = ";" if os.name == "nt" else ":"
    args = [
        sys.executable,
        "-m",
        "PyInstaller",
        "--noconfirm",
        "--clean",
        "--windowed",
        "--onedir",
        "--name",
        APP_EXE,
        "--icon",
        str(resources / "app.ico"),
        "--version-file",
        str(version_file),
        "--paths",
        str(ROOT / "src"),
        "--add-data",
        f"{resources}{sep}desktop_organizer/resources",
        "--collect-submodules",
        "desktop_organizer.tools",
        "--distpath",
        str(DIST),
        "--workpath",
        str(WORK / "pyinstaller"),
        "--specpath",
        str(WORK),
        # Qt modules the app does not use; keeps the download smaller.
        *[
            arg
            for module in ("PySide6.QtQml", "PySide6.QtQuick", "PySide6.QtPdf", "tkinter")
            for arg in ("--exclude-module", module)
        ],
        str(BUILD / "entry.py"),
    ]
    subprocess.run(args, check=True, cwd=ROOT)
    app_dir = DIST / APP_EXE
    prune_qt_translations(app_dir)
    return app_dir


def prune_qt_translations(app_dir: Path) -> None:
    """Keep only Qt's German and English translations (the app supports nothing else)."""
    for folder in app_dir.rglob("translations"):
        if folder.parent.name != "Qt":
            continue
        for file in folder.glob("*.qm"):
            if not re.search(r"_(de|en)\.qm$", file.name):
                file.unlink()


def make_portable_zip(app_dir: Path, version: str) -> Path:
    target = DIST / f"DesktopOrganizer-{version}-portable.zip"
    root_name = f"DesktopOrganizer-{version}"
    with zipfile.ZipFile(target, "w", compression=zipfile.ZIP_DEFLATED) as archive:
        for file in sorted(app_dir.rglob("*")):
            if file.is_file():
                archive.write(file, f"{root_name}/{file.relative_to(app_dir).as_posix()}")
        # The empty data folder is what switches the app into portable mode.
        archive.writestr(f"{root_name}/data/", "")
    return target


def find_iscc() -> str | None:
    found = shutil.which("iscc")
    if found:
        return found
    for base in (os.environ.get("PROGRAMFILES(X86)"), os.environ.get("PROGRAMFILES")):
        if base:
            candidate = Path(base) / "Inno Setup 6" / "ISCC.exe"
            if candidate.exists():
                return str(candidate)
    return None


def make_installer(version: str) -> Path:
    iscc = find_iscc()
    if iscc is None:
        raise SystemExit("Inno Setup (iscc) not found. Install Inno Setup 6 or use --no-installer.")
    subprocess.run(
        [
            iscc,
            f"/DAppVersion={version}",
            f"/DAppPublisher={PUBLISHER}",
            f"/DSourceDir={DIST / APP_EXE}",
            f"/DOutputDir={DIST}",
            f"/DIconFile={ROOT / 'src' / 'desktop_organizer' / 'resources' / 'app.ico'}",
            str(BUILD / "installer.iss"),
        ],
        check=True,
        cwd=ROOT,
    )
    return DIST / f"DesktopOrganizer-{version}-setup.exe"


def write_checksums(files: list[Path]) -> Path:
    target = DIST / "SHA256SUMS.txt"
    lines = []
    for file in files:
        digest = hashlib.sha256(file.read_bytes()).hexdigest()
        lines.append(f"{digest}  {file.name}")
    target.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return target


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--no-installer", action="store_true")
    args = parser.parse_args()

    version = read_version()
    print(f"Building Desktop Organizer {version}")
    if DIST.exists():
        shutil.rmtree(DIST)
    app_dir = run_pyinstaller(write_version_file(version))
    release_files = [make_portable_zip(app_dir, version)]
    if not args.no_installer:
        release_files.append(make_installer(version))
    checksums = write_checksums(release_files)
    for file in [*release_files, checksums]:
        print(f"  {file.relative_to(ROOT)}  ({file.stat().st_size / 1_048_576:.1f} MB)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
